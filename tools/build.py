#!/usr/bin/env python3
"""Merge data/*.json into data.js for the site. Usage: python3 tools/build.py <data_dir> <out.js>"""
import json, sys, os, re

src, out = sys.argv[1], sys.argv[2]
J = lambda f: json.load(open(os.path.join(src, f), encoding='utf-8')) if os.path.exists(os.path.join(src, f)) else []

base = J('base.json')
guides = J('susi.json') + J('jungsi.json') + J('etc.json')
univ = J('univ1.json') + J('univ2.json')

SEOUL = "가톨릭대 건국대학교 경희대 고려대학교 광운대 국민대 덕성여자 동국대학교 동덕여자 명지대 삼육대 상명대학교 서강대 서경대 서울과학기술 서울대학교 서울시립 서울여자 성공회 성균관 성신여자 세종대 숙명여자 숭실대 연세대학교 이화여자 중앙대 총신대 한국성서 한국외국어 한성대 한양대학교 홍익대학교 서울교육".split()
GYEONGIN = "가천대 강남대 경기대 대진대 성결대 수원대 신한대 아주대 안양대 용인대 을지대 인천대 인하대 중부대학교(고양) 차 의과학 평택대 한경국립 한국공학 한국항공 한신대 한양대학교(ERICA) 협성대 화성의과학 경인교육 경동대 동양대학교(동두천)".split()
GANGWON = "강원대 한림대 연세대학교(미래) 춘천교육".split()
CHUNG = "건국대학교(글로컬) 고려대학교(세종) 공주대 국립공주 단국대학교(천안) 상명대학교(천안) 충남대 충북대 한국기술교육 한국교원 한국교통 홍익대학교(세종) 공주교육 청주교육 강서대".split()
GYEONG = "경북대 경상국립 동국대학교(WISE) 부산대 대구교육 부산교육 진주교육 포항공과 대구경북과학 울산과학".split()
JEOLLA = "전남대 전북대 제주대 광주교육 전주교육 광주과학 한국에너지".split()

def region(n):
    for key, lst in (("충청·세종", CHUNG), ("강원", GANGWON), ("경상", GYEONG), ("전라·제주", JEOLLA)):
        if any(n.startswith(k) or k in n for k in lst):
            if key == "강원" and n.startswith("강원대학교(강릉"):
                return "강원"
            return key
    if any(n.startswith(k) for k in GYEONGIN) or n == "한양대학교(ERICA)":
        return "경기·인천"
    if "사관" in n or "경찰" in n:
        return "특수목적"
    return "서울" if any(n.startswith(k) for k in SEOUL) else "기타"

def kind(n):
    if ("교육대학교" in n and "기술교육" not in n) or n == "한국교원대학교": return "교육대"
    if any(k in n for k in ("과학기술원", "POSTECH", "KENTECH", "DGIST", "GIST", "UNIST", "KAIST")): return "과학기술원"
    if "사관" in n or "경찰" in n: return "특수목적"
    return "일반대"

def fix_region(n, r):
    special = {"한양대학교(ERICA)": "경기·인천", "중부대학교(고양)": "경기·인천", "동양대학교(동두천)": "경기·인천", "경동대학교": "경기·인천",
               "강서대학교": "서울", "단국대학교": "경기·인천", "가톨릭대학교": "경기·인천", "육군사관학교": "특수목적", "해군사관학교": "특수목적", "공군사관학교": "특수목적",
               "국군간호사관학교": "특수목적", "경찰대학교": "특수목적", "한국과학기술원(KAIST)": "충청·세종",
               "광주과학기술원(GIST)": "전라·제주", "한국에너지공과대학교(KENTECH)": "전라·제주",
               "대구경북과학기술원(DGIST)": "경상", "울산과학기술원(UNIST)": "경상", "포항공과대학교(POSTECH)": "경상",
               "연세대학교(미래)": "강원", "강원대학교(춘천)": "강원", "강원대학교(강릉･원주)": "강원", "한림대학교": "강원"}
    return special.get(n, r)

for i, u in enumerate(univ):
    n = u.get('name', '')
    u['id'] = 'u%03d' % i
    u['region'] = fix_region(n, region(n))
    u['kind'] = kind(n)
    types = sorted({s.get('type', '') for s in u.get('susi', []) if s.get('type')})
    u['types'] = types
    u['susiTotal'] = sum(s.get('count', 0) or 0 for s in u.get('susi', []) if isinstance(s.get('count'), int))

with open(out, 'w', encoding='utf-8') as f:
    f.write('// generated by tools/build.py — do not edit by hand\n')
    f.write('window.BASE=' + json.dumps(base, ensure_ascii=False) + ';\n')
    f.write('window.GUIDES=' + json.dumps(guides, ensure_ascii=False) + ';\n')
    f.write('window.UNIV=' + json.dumps(univ, ensure_ascii=False) + ';\n')
print('guides', len(guides), 'univ', len(univ))
from collections import Counter
print(Counter(u['region'] for u in univ), Counter(u['kind'] for u in univ))
